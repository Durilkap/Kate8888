#!/usr/bin/env python3
"""Титры рилса 39 по словам: время слов из локальной расшифровки дубля (work/r39/units.json), текст выверен по сценарию.
Голос в ролике начинается с 0,85 с дубля (tools/prepare_r39.py). Пишет src/PlatyeCards.ts. Использование (из video/):
python3 tools/cards_r39.py"""
import json

U = json.load(open('work/r39/units.json'))
T0 = 0.85
FPS = 30
# по фразам (единицам речи): карточки -> строки (не длиннее 20 знаков); '*' = слово на плашке
TEXT = [
    [['Сейчас меня', '*возненавидят все'], ['мамы и подружки', 'невест,'], ['но я скажу:']],
    [['платье мечты', 'начинается'], ['*не *с *примерки.'], ['Расскажу, как я', 'пришла к платью,'], ['которое было', '*только *моим.'],
     ['Я не мерила', 'ни одного'], ['салонного платья.'], ['Моё сшили', '*на *заказ.'], ['Просто', '*посмотрите.']],
    [['*Первое.', 'Решите, какой вы'], ['хотите себя', 'чувствовать'], ['в этот день.']],
    [['Не фасон,', 'а *ощущение.']],
    [['*Второе.', 'Опишите это'], ['нейросети, и она', 'нарисует'], ['три эскиза', 'по вашему описанию.'], ['Промт я дам.']],
    [['*Третье.', 'С эскизом'], ['к мастеру, которому', 'вы доверяете.'], ['*Четвёртое.'], ['Детали делают', 'образ вашим:'],
     ['*корсет, *перчатки,', '*туфли.'], ['Это не про фасон.'], ['Это про то, чтобы', 'в главный день'], ['*быть *собой.'], ['Хотите промт?']],
    [['Пишите *ПЛАТЬЕ', 'в комментариях']],
]


def main():
    cards = []
    for u, cs in zip(U, TEXT):
        words = [w for c in cs for l in c for w in l.split(' ')]
        assert len(words) == len(u['words']), (u['k'], len(words), len(u['words']))
        k = 0
        for c in cs:
            lines = []
            for l in c:
                ws = []
                for w in l.split(' '):
                    ws.append({'t': w.lstrip('*'), 'at': max(0, round((u['words'][k]['s'] - T0) * FPS)), 'a': w.startswith('*')})
                    k += 1
                lines.append({'big': False, 'words': ws})
            cards.append({'from': max(0, lines[0]['words'][0]['at'] - 2), 'full': False, 'lines': lines})
    cards[0]['from'] = 0
    ts = ("// Титры рилса 39 по словам (tools/cards_r39.py): время из локальной расшифровки дубля, текст по сценарию.\n"
          "import {Card} from './WordCaptions';\n\nexport const PLATYE_CARDS: Card[] = " + json.dumps(cards, ensure_ascii=False) + ";\n")
    open('src/PlatyeCards.ts', 'w', encoding='utf-8').write(ts)
    print(len(cards), 'экранов')


if __name__ == '__main__':
    main()
