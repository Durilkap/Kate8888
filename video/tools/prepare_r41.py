#!/usr/bin/env python3
"""Рилс 41 «Леди или спортсменка?» (21.11): нарезка из готовых видео Кати, без новой съёмки.

Исходники (work/r41/src, в git не попадают): c1 блузка и каблуки дома у зеркала (4K 120 к/с), c2 чёрное платье
в примерочной (4K 120 к/с; первые 6,5 с с мужчиной за спиной не берём), c3 зелёный пуховик и легинсы, c4 белый
комбинезон в зале, c5 чёрный пуховик и кепка. Пишет public/r41/<имя>.mp4, 1080x1920 30 к/с без звука.
Замедление берём из 120 к/с (плавно). Использование (из video/): python3 tools/prepare_r41.py
"""
import subprocess

SRC = 'work/r41/src'
# (файл, начало, конец, имя, скорость)
CLIPS = [
    ('c1.mov', 0.6, 2.8, 'l1', 1.0),     # леди: блузка и каблуки, идёт к зеркалу
    ('c4.mov', 0.0, 1.9, 's1', 0.75),    # спорт: комбинезон в зале, губы сомкнуты, лёгкое замедление (дольше: «Не уборка. Не готовка.» и «Я не убираюсь и не готовлю»)
    # Катя 21.11: кадры платья спереди с неуверенностью заменить на кадры с отражением в зеркале (спиной, видно в зеркале)
    ('c2.mov', 11.0, 12.8, 'l2', 1.0),   # леди: идёт к зеркалу, в зеркале отражение
    ('c2.mov', 14.6, 15.4, 'l3', 0.45),  # леди: руки в волосах у зеркала, замедление («Леди?»); без кадров с приоткрытым ртом в отражении
    # Катя 21.11: спортсменка в финале и в «Или спортсменка?» в кепке и очках (ярче), а не в комбинезоне
    # Катя 21.11: только эстетичные кадры, без открытого рта (в этом видео она говорит): 2,15-2,95 с губы сомкнуты
    ('c5.mov', 2.15, 2.95, 's2', 0.5),  # спорт: кепка, очки, пуховик, спокойный взгляд («Или спортсменка?»)
    ('c1.mov', 10.0, 10.6, 'q1', 1.0),   # быстрая смена образов под бит
    ('c3.mov', 0.8, 1.4, 'q2', 1.0),   # губы сомкнуты (проверка лиц 21.11)
    ('c2.mov', 16.0, 16.6, 'q3', 1.0),  # отражение, лицо спокойное
    ('c5.mov', 7.1, 7.7, 'q4', 1.0),   # поправляет очки, губы сомкнуты
    ('c1.mov', 6.0, 6.6, 'q5', 1.0),
    ('c4.mov', 0.5, 1.1, 'q6', 1.0),   # губы сомкнуты
    ('c1.mov', 1.8, 2.6, 'sl', 0.333),  # разделённый экран: леди (1), белый пиджак в полный рост, замедление из 120 к/с (голова не уходит за край) (Катя 22.11: в видео тоже пиджак, не платье со спины)
    ('c5.mov', 2.5, None, 'sr', 'still'),  # разделённый экран и обложка: спортсменка (2), стоп-кадр 2,5 с (рот закрыт)
]


def main():
    for f, a, b, n, sp in CLIPS:
        if sp == 'still':  # стоп-кадр на 2,4 с с лёгким приближением
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(a), '-i', f'{SRC}/{f}', '-frames:v', '1', '-an',
                            '-vf', 'scale=1080:1920:flags=lanczos', f'work/r41/{n}.png'], check=True)
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-loop', '1', '-t', '3', '-i', f'work/r41/{n}.png', '-an',
                            '-vf', "scale=1188:2112,zoompan=z='1+0.0006*on':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d=1:s=1080x1920:fps=30,format=yuv420p",
                            '-frames:v', '72', '-c:v', 'libx264', '-crf', '15', '-preset', 'medium', f'public/r41/{n}.mp4'], check=True)
            continue
        vf = f'setpts=PTS/{sp},scale=1080:1920:flags=lanczos,fps=30,format=yuv420p'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(a), '-to', str(b), '-i', f'{SRC}/{f}', '-an',
                        '-vf', vf, '-c:v', 'libx264', '-crf', '15', '-preset', 'medium', '-map_metadata', '-1',
                        f'public/r41/{n}.mp4'], check=True)
    print('кусков', len(CLIPS))


if __name__ == '__main__':
    main()
