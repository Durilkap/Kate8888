#!/usr/bin/env python3
"""Рилс 41 «Леди или спортсменка?» (21.11): нарезка из готовых видео Кати, без новой съёмки.

Исходники (work/r41/src, в git не попадают): c1 блузка и каблуки дома у зеркала (4K 120 к/с), c2 чёрное платье
в примерочной (4K 120 к/с; первые 6,5 с с мужчиной за спиной не берём), c3 зелёный пуховик и легинсы, c4 белый
комбинезон в зале, c5 чёрный пуховик и кепка. Пишет public/r41/<имя>.mp4, 1080x1920 30 к/с без звука.
Замедление берём из 120 к/с (плавно). Использование (из video/): python3 tools/prepare_r41.py
"""
import subprocess

SRC = 'work/r41/src'
# (файл, начало, конец, имя, скорость)
CLIPS = [
    ('c1.mov', 0.6, 2.8, 'l1', 1.0),     # леди: блузка и каблуки, идёт к зеркалу
    ('c5.mov', 6.9, 8.4, 's1', 1.0),     # спорт: пуховик и кепка, подходит к зеркалу
    ('c2.mov', 20.1, 21.3, 'l2', 0.6),   # леди: платье, идёт к камере, замедление
    ('c2.mov', 18.0, 19.2, 'l3', 0.6),   # леди: платье, поворот, замедление («Леди?»)
    ('c4.mov', 6.2, 7.8, 's2', 1.0),     # спорт: комбинезон в зале, идёт к зеркалу («Или спортсменка?»)
    ('c1.mov', 10.0, 10.6, 'q1', 1.0),   # быстрая смена образов под бит
    ('c3.mov', 2.5, 3.1, 'q2', 1.0),
    ('c2.mov', 21.3, 21.9, 'q3', 1.0),
    ('c5.mov', 10.8, 11.4, 'q4', 1.0),
    ('c1.mov', 6.0, 6.6, 'q5', 1.0),
    ('c4.mov', 2.4, 3.0, 'q6', 1.0),
    ('c2.mov', 19.8, 21.0, 'sl', 0.5),   # разделённый экран: леди (1)
    ('c4.mov', 0.4, 2.8, 'sr', 1.0),     # разделённый экран: спортсменка (2)
]


def main():
    for f, a, b, n, sp in CLIPS:
        vf = f'setpts=PTS/{sp},scale=1080:1920:flags=lanczos,fps=30,format=yuv420p'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(a), '-to', str(b), '-i', f'{SRC}/{f}', '-an',
                        '-vf', vf, '-c:v', 'libx264', '-crf', '15', '-preset', 'medium', '-map_metadata', '-1',
                        f'public/r41/{n}.mp4'], check=True)
    print('кусков', len(CLIPS))


if __name__ == '__main__':
    main()
