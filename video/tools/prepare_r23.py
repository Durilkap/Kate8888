#!/usr/bin/env python3
"""Рилс «Угадай продукт по кусочку этикетки» (10.11): видео Кати из магазина.

Для каждого продукта два куска: загадка (кусочек этикетки крупно, цифровое приближение 4K) и ответ (продукт целиком).
Кадры с ценниками и логотипом магазина не берутся. Крупное название марки на розовой бутылке уходит за край
(приближение вниз). Звук не переносится: музыку Катя добавит сама.

Использование (из папки video/):
  python3 tools/prepare_r23.py work/r23/src public/r23
"""
import subprocess
import sys
from pathlib import Path

W, H, FPS = 1080, 1920, 30

# имя: (файл, начало, конец, скорость, приближение, центр x, центр y)
CLIPS = {
    'g1': ('v7502.mov', 0.00, 1.40, 1.0, 1.3, 0.5, 0.6),   # бутылка 1: состав и цифры крупно
    'a1': ('v7502.mov', 3.60, 5.20, 1.0, 1.0, 0.5, 0.5),   # бутылка 1 целиком
    'g2': ('v7503.mov', 0.40, 1.80, 1.0, 2.0, 0.35, 0.55),  # бутылка 2: розовая жидкость вплотную
    'a2': ('v7503.mov', 2.00, 3.80, 1.0, 1.0, 0.5, 0.5),   # бутылка 2 целиком (без ценников)
    'g3': ('v7505.mov', 0.00, 1.40, 1.0, 1.6, 0.55, 0.4),  # упаковка 3: рисунок свиньи
    'a3': ('v7505.mov', 3.00, 4.80, 1.0, 1.0, 0.5, 0.5),   # упаковка 3 целиком
    'g4': ('v7506.mov', 2.60, 3.80, 1.0, 1.5, 0.5, 0.45),  # банка 4: узор из помидоров
    'a4': ('v7506.mov', 0.80, 2.40, 1.0, 1.0, 0.5, 0.5),   # банка 4 целиком
    'g5': ('v7507.mov', 0.00, 1.40, 1.0, 2.0, 0.6, 0.15),  # бутылка 5: тёмная жидкость и пузырьки у горлышка
    'a5': ('v7507.mov', 2.00, 3.80, 1.0, 1.0, 0.5, 0.5),   # бутылка 5 целиком
    'g6': ('v7508.mov', 1.00, 2.40, 1.0, 1.7, 0.2, 0.75),  # бутылка 6: банан на розовой этикетке (название марки выше кадра)
    'a6': ('v7508.mov', 2.50, 4.20, 1.0, 1.3, 0.5, 1.0),   # бутылка 6: приближение вниз, название марки сверху за краем
    'end': ('vwink.mp4', 2.80, 7.20, 1.0, 1.0, 0.5, 0.5),  # Катя в магазине берёт продукт с полки (финал)
}


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    dst.mkdir(parents=True, exist_ok=True)
    for name, (f, a, b, speed, z, ox, oy) in CLIPS.items():
        vf = f'crop=iw/{z}:ih/{z}:(iw-iw/{z})*{ox}:(ih-ih/{z})*{oy},' if z != 1.0 else ''
        vf += f'scale={W}:{H}:force_original_aspect_ratio=increase:flags=lanczos,crop={W}:{H}'
        if speed != 1.0:
            vf += f',setpts=PTS/{speed}'
        vf += f',fps={FPS},format=yuv420p'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{a}', '-to', f'{b}', '-i', str(src / f), '-an', '-vf', vf,
                        '-c:v', 'libx264', '-crf', '15', '-preset', 'medium', '-map_metadata', '-1', str(dst / f'{name}.mp4')], check=True)
        print(name)


if __name__ == '__main__':
    main()
