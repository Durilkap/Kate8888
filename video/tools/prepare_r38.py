#!/usr/bin/env python3
"""Рилс 38 (челлендж, день 3, вопрос): нарезка танца Кати для VoprosReel.

Катя 19.11 прислала 5 видео танца (iPhone 4K HDR, 60 и 30 к/с): два в белом платье, три в красном топе.
Выбран образ в красном: взгляд через плечо, взмах волос, танец спиной у сцены.
Исходники лежат в work/r38/src (в git не попадают). Использование (из папки video/): python3 tools/prepare_r38.py
"""
import subprocess

SRC = 'work/r38/src'
# (файл, начало, конец, имя, скорость, кроп из 2160x3840 или None)
CLIPS = [
    # Катя 19.11: кадры лицом к камере в полный рост и с наклоном (грудь) не нравятся. Оставлены только спина,
    # бок, взмах волос и взгляд через плечо. Всё из IMG_3037 (Катя одна у сцены) и финал из IMG_3038.
    ('IMG_3037.MOV', 1.0, 1.6, 'k1', 1.0, None),     # в три четверти, оглядывается на камеру с улыбкой
    ('IMG_3037.MOV', 12.5, 13.5, 'k3', 0.6, None),   # разворот со взмахом волос, замедление
    ('IMG_3037.MOV', 13.5, 14.4, 'k5', 1.0, None),   # спиной, волосы, обычная скорость (после замедления)
    ('IMG_3037.MOV', 15.2, 17.6, 'k6', 1.0, None),   # спиной у сцены, танец, руки вверх
    # взгляд через плечо с улыбкой, финал; справа стоят посторонние девушки с телефоном: кроп левой части кадра
    ('IMG_3038.MOV', 19.8, 20.95, 'k4', 0.8, (1566, 2784, 0, 500)),  # y=500: лицо в начале выше вопроса
]

# Катя 19.11: «Есть кадры, где грудь смотрится красиво. И хочу ещё одно видео, где я в топике танцую».
# Версия 7: только белый топик и юбка (IMG_2207 балкон, IMG_2208 светящийся танцпол).
CLIPS_TOPIK = [
    ('IMG_2207.MOV', 24.6, 25.55, 't1', 0.7, None),   # танцует, поворачивается к камере с улыбкой
    ('IMG_2208.MOV', 4.3, 5.93, 't2', 1.0, (1215, 2160, 372, 700)),  # танцпол, обе руки вверх, улыбка; кроп к Кате без танцующих рядом
    ('IMG_2207.MOV', 4.6, 6.7, 't3', 0.8, None),      # в профиль у перил, в полный рост
    ('IMG_2207.MOV', 25.55, 26.65, 't4', 0.8, None),   # разворот, спина, хвост с платком
]


def main():
    for f, a, b, n, sp, crop in CLIPS + CLIPS_TOPIK:
        cr = 'crop=%d:%d:%d:%d,' % crop if crop else ''
        vf = f'setpts=PTS/{sp},{cr}scale=1080:1920:flags=lanczos,fps=30,format=yuv420p'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(a), '-to', str(b), '-i', f'{SRC}/{f}', '-an',
                        '-vf', vf, '-c:v', 'libx264', '-crf', '15', '-preset', 'medium', '-map_metadata', '-1',
                        f'public/r38/{n}.mp4'], check=True)
    print('кусков', len(CLIPS) + len(CLIPS_TOPIK))


if __name__ == '__main__':
    main()
