#!/usr/bin/env python3
"""Титры рилса 37 по словам: время слов из расшифровки выбранного дубля, текст выверен вручную.
Пишет src/ProshuCards.ts. Использование (из папки video/): python3 tools/cards_r37.py"""
import json

W = json.load(open('work/r37/words.json'))
TL = json.load(open('public/r37/timeline.json'))
SENT = json.load(open('work/r37/sent.json'))
RANGE = {
    't1': [(0, 12), (13, 29), (30, 38), (39, 49), (50, 62), (63, 68), None, (69, 78), (79, 95), (96, 111), (112, 117), (118, 126)],
    't2': [(0, 12), (13, 29), (30, 38), (39, 49), (50, 62), (63, 68), (69, 74), (75, 84), (85, 101), (102, 118), (119, 124), (125, 133)],
    't3': [(0, 12), (13, 29), (30, 38), (39, 49), (50, 62), (63, 68), (69, 74), (75, 84), (85, 101), (102, 118), (119, 124), (125, 133)],
}
# фразы: карточки -> строки -> слова; '*' в начале слова = выделить плашкой; строка с '!' в начале = крупно
# версия 2 (куратор 19.11): все строки одного размера, не длиннее 20 знаков, без крупных строк
TEXT = [
    [['Самый простой способ', 'получать от *мужчины'], ['внимание, заботу', 'и подарки,'], ['это *тупо *попросить']],
    [['Я знаю, что вы', 'сейчас скажете:'], ['я пробовала,', 'намекала, говорила,'], ['а он всё равно', 'меня не слышит']],
    [['Это потому, что', 'вы просите'], ['*не *по *той *формуле']],
    [['Намёк, это', 'не просьба.'], ['А просьба с упрёком,', 'это уже *претензия']],
    [['У меня за плечами', '*два *брака,'], ['где я ждала,', 'что догадаются.'], ['Не догадались.']],
    [['Потом я поняла,', 'как это работает.']],
    [['Сейчас я прошу', '*прямо *и *спокойно.']],
    [['И да, *мне *дарят:'], ['цветы без повода,', 'украшения,'], ['время вдвоём.']],
    [['Всё, что вам нужно,'], ['это одна', '*правильная *фраза:'], ['что я хочу,', 'когда и как'], ['мне будет приятно.']],
    [['Я уже сделала', 'это за вас:'], ['три фразы,', 'как просить'], ['без намёков', 'и упрёков,'], ['и промт для ChatGPT.']],
    [['Хотите забрать,', 'пишите *ПРОШУ'], ['в комментариях']],
    [['Попробуйте неделю.'], ['Вы удивитесь,', 'насколько *легче'], ['становится', 'вам обоим 🤍']],
]
FPS = 30


def main():
    cards = []
    for i, cs in enumerate(TEXT):
        piece = [x for x in TL if x['s'] == i]
        take = piece[0]['take']
        src0, out0 = piece[0]['src'][0], piece[0]['out'][0]
        src1, out1 = piece[-1]['src'][1], piece[-1]['out'][1]
        r = RANGE[take][i]
        asr = W[take][r[0]:r[1] + 1]
        disp = [w for c in cs for l in c for w in l.lstrip('!').split(' ')]
        n = len(disp)
        times = []
        for k in range(n):
            if k < len(asr):
                t = asr[k]['s']
            else:  # слов больше, чем распознано (ChatGPT): сразу после последнего
                t = asr[-1]['e'] + 0.05 * (k - len(asr) + 1)
            times.append(round((out0 + (t - src0)) * FPS))
        k = 0
        for c in cs:
            lines = []
            for l in c:
                big = l.startswith('!')
                words = []
                for w in l.lstrip('!').split(' '):
                    a = w.startswith('*')
                    words.append({'t': w.lstrip('*'), 'at': times[k], 'a': a})
                    k += 1
                lines.append({'big': big, 'words': words})
            cards.append({'from': lines[0]['words'][0]['at'] - 2, 'full': False, 'lines': lines})
        assert k == n, (i, k, n)
    cards[0]['from'] = 0
    ts = ("// Титры рилса 37 по словам (tools/cards_r37.py): время из локальной расшифровки дубля, текст выверен вручную.\n"
          "import {Card} from './WordCaptions';\n\nexport const PROSHU_CARDS: Card[] = " + json.dumps(cards, ensure_ascii=False) + ";\n")
    open('src/ProshuCards.ts', 'w', encoding='utf-8').write(ts)
    print(len(cards), 'экранов')


if __name__ == '__main__':
    main()
